import { z } from "zod";

type ApiResult = Promise<{ data: unknown; error: unknown }>;
export type PrivateBetaMfaApi = Readonly<{
  listFactors: () => ApiResult;
  getAuthenticatorAssuranceLevel: () => ApiResult;
  enroll: (value: { factorType: "totp"; friendlyName: string }) => ApiResult;
  challengeAndVerify: (value: { factorId: string; code: string }) => ApiResult;
  recoverUnverifiedEnrollment?: (value: { factorId: string; confirmed: true }) => ApiResult;
}>;
const factor = z.object({ id: z.uuid(), factor_type: z.string(), status: z.enum(["verified", "unverified"]) });
const factors = z.object({ all: z.array(factor).max(10), totp: z.array(factor).max(10) });
const assurance = z.object({ currentLevel: z.enum(["aal1", "aal2"]), currentAuthenticationMethods: z.array(z.union([z.string().max(80), z.object({ method: z.string(), timestamp: z.number().int().nonnegative().safe() })])).max(20) });
const enrollment = z.object({ id: z.uuid(), type: z.literal("totp"), totp: z.object({ qr_code: z.unknown().optional(), secret: z.string().regex(/^[A-Za-z2-7]{16,128}={0,6}$/u) }) });
export type PrivateBetaMfaFactor = Readonly<{ id: string; label: number }>;
export type PrivateBetaMfaFailure = "UNAVAILABLE" | "INVALID_CODE" | "NO_FACTOR" | "ENROLLMENT_PENDING" | "ALREADY_ENROLLED" | "VERIFICATION_NOT_CONFIRMED" | "RECOVERY_CONFIRMATION_REQUIRED" | "RECOVERY_REAUTH_REQUIRED" | "RECOVERY_BLOCKED" | "RECOVERY_NOT_CONFIRMED";

/** Only provider QR vector markup; no active markup, remote image or unsafe HTML insertion. */
export function privateBetaMfaQrUri(raw: string) {
  if (raw.length > 524288) throw Error("MFA_QR_INVALID");
  const prefix = "data:image/svg+xml;utf-8,";
  let svg = raw.startsWith(prefix) ? raw.slice(prefix.length) : raw;
  if (!svg.trimStart().startsWith("<")) svg = decodeURIComponent(svg);
  // Supabase Auth's goqrsvg/SVGo output includes these inert wrappers and
  // fixed black/white styles. Project only those known forms into passive SVG;
  // arbitrary XML processing instructions, CSS or linked content stay rejected.
  svg = svg.replace(/^\s*<\?xml\s+version="1\.0"\s*\?>\s*/u, "").replace(/^\s*<!-- Generated by SVGo -->\s*/u, "")
    .replace(/\sxmlns:xlink="http:\/\/www\.w3\.org\/1999\/xlink"/gu, "")
    .replace(/\sstyle="fill:(black|white);stroke:none"/gu, ' fill="$1" stroke="none"');
  if (!/^\s*<svg\b[\s\S]*<\/svg>\s*$/u.test(svg) || /<!|<\?|\bon[a-z]+\s*=|\bhref\s*=|url\s*\(|javascript:|<style\b/iu.test(svg)) throw Error("MFA_QR_INVALID");
  const tags = [...svg.matchAll(/<\/?([A-Za-z][A-Za-z0-9:_-]*)\b/gu)];
  if (!tags.length || tags.length > 32768 || tags.some(v => !["svg", "path", "rect", "g", "circle"].includes(v[1]!))) throw Error("MFA_QR_INVALID");
  const stack: string[] = []; let end = 0;
  for (const match of svg.matchAll(/<(\/?)([A-Za-z][A-Za-z0-9:_-]*)([^<>]*?)(\/?)>/gu)) {
    if (svg.slice(end, match.index).trim()) throw Error("MFA_QR_INVALID");
    const closing = match[1] === "/", name = match[2]!, tail = match[3]!;
    if (closing) { if (tail.trim() || match[4] || stack.pop() !== name) throw Error("MFA_QR_INVALID"); }
    else {
      if (name === "svg" && (stack.length || end > 0 && svg.slice(0, end).trim())) throw Error("MFA_QR_INVALID");
      let at = 0; const seen = new Set<string>();
      for (const attribute of tail.matchAll(/\s+([A-Za-z_:][A-Za-z0-9_:.-]*)\s*=\s*(?:"([^"]*)"|'([^']*)')/gu)) {
        if (tail.slice(at, attribute.index).trim()) throw Error("MFA_QR_INVALID");
        const key = attribute[1]!, value = attribute[2] ?? attribute[3] ?? ""; at = attribute.index + attribute[0].length;
        if (seen.has(key)) throw Error("MFA_QR_INVALID"); seen.add(key);
        const numeric = /^-?[0-9]{1,6}(?:\.[0-9]{1,6})?$/u;
        const valid = key === "xmlns" ? name === "svg" && value === "http://www.w3.org/2000/svg"
          : ["width", "height", "stroke-width", "x", "y", "rx", "ry", "cx", "cy", "r"].includes(key) ? numeric.test(value)
          : ["fill", "stroke"].includes(key) ? /^(?:none|black|white|#[a-f0-9]{3}|#[a-f0-9]{6}|#[a-f0-9]{8})$/iu.test(value)
          : key === "viewBox" ? /^-?[0-9.]+(?:[ ,]+-?[0-9.]+){3}$/u.test(value)
          : key === "d" ? /^[MmLlHhVvCcSsQqTtAaZz0-9+.,eE\s-]+$/u.test(value)
          : key === "transform" ? /^(?:(?:translate|scale|matrix|rotate)\([0-9+.,\s-]+\)\s*)+$/u.test(value)
          : key === "shape-rendering" && /^(?:crispEdges|geometricPrecision|auto|optimizeSpeed)$/u.test(value);
        if (!valid) throw Error("MFA_QR_INVALID");
      }
      if (tail.slice(at).trim()) throw Error("MFA_QR_INVALID");
      if (!match[4]) stack.push(name);
    }
    end = match.index + match[0].length;
  }
  if (stack.length || svg.slice(end).trim()) throw Error("MFA_QR_INVALID");
  return prefix + encodeURIComponent(svg);
}
/** UX coordinator only. Supabase's verified session and SQL MFA/role guards remain authoritative. */
export function createPrivateBetaMfaController(api: PrivateBetaMfaApi, now: () => number = Date.now) {
  let ownEnrollment: string | null = null;
  let recoverableEnrollment: string | null = null, mutating = false;
  async function read() {
    const result = await api.listFactors();
    if (result.error) throw Error("UNAVAILABLE");
    const value = factors.parse(result.data);
    const pending = value.all.filter(f => f.factor_type === "totp" && f.status === "unverified");
    const verified = value.totp.filter(f => f.factor_type === "totp" && f.status === "verified");
    const selected: PrivateBetaMfaFactor[] = verified.map((f, index) => ({ id: f.id, label: index + 1 }));
    const level = await api.getAuthenticatorAssuranceLevel();
    if (level.error) throw Error("UNAVAILABLE");
    const current = assurance.parse(level.data), clock = now();
    const fresh = Number.isFinite(clock) && current.currentLevel === "aal2" && current.currentAuthenticationMethods.some(m => typeof m !== "string" && m.method === "totp" && m.timestamp * 1000 <= clock && clock - m.timestamp * 1000 <= 300000);
    recoverableEnrollment = !value.all.some(f => f.status === "verified") && pending.length === 1 ? pending[0]!.id : null;
    if (ownEnrollment && !pending.some(f => f.id === ownEnrollment)) ownEnrollment = null;
    return { factors: selected, fresh, pendingEnrollment: value.all.some(f => f.factor_type === "totp" && f.status === "unverified") };
  }
  return Object.freeze({
    async inspect() { try { return { ok: true as const, ...await read() }; } catch { return { ok: false as const, error: "UNAVAILABLE" as const }; } },
    async enroll() {
      if (mutating) return { ok: false as const, error: "UNAVAILABLE" as const };
      if (ownEnrollment) return { ok: false as const, error: "ENROLLMENT_PENDING" as const };
      mutating = true;
      try {
        const current = await read();
        if (current.factors.length) return { ok: false as const, error: "ALREADY_ENROLLED" as const };
        if (current.pendingEnrollment) return { ok: false as const, error: "ENROLLMENT_PENDING" as const };
        const result = await api.enroll({ factorType: "totp", friendlyName: "Polat VIP private beta" });
        if (result.error) throw Error("unavailable");
        const value = enrollment.parse(result.data);
        ownEnrollment = value.id;
        recoverableEnrollment = value.id;
        let qr: string | null = null;
        try { if (typeof value.totp.qr_code === "string") qr = privateBetaMfaQrUri(value.totp.qr_code); } catch { /* A rejected QR must not strand a valid enrollment; show the private manual key. */ }
        return { ok: true as const, factorId: value.id, qr, secret: value.totp.secret };
      } catch { return { ok: false as const, error: "UNAVAILABLE" as const }; }
      finally { mutating = false; }
    },
    async recover(confirmed: boolean) {
      if (!confirmed) return { ok: false as const, error: "RECOVERY_CONFIRMATION_REQUIRED" as const };
      if (mutating || !recoverableEnrollment) return { ok: false as const, error: "RECOVERY_BLOCKED" as const };
      mutating = true;
      try {
        const result = await api.listFactors(); if (result.error) throw Error();
        const all = factors.parse(result.data).all, pending = all.filter(f => f.factor_type === "totp" && f.status === "unverified");
        if (all.some(f => f.status === "verified") || pending.length !== 1 || pending[0]!.id !== recoverableEnrollment || !api.recoverUnverifiedEnrollment) return { ok: false as const, error: "RECOVERY_BLOCKED" as const };
        const recovered = await api.recoverUnverifiedEnrollment({ factorId: pending[0]!.id, confirmed: true });
        if (recovered.error) {
          const failure = z.object({ code: z.enum(["RECOVERY_REAUTH_REQUIRED", "RECOVERY_BLOCKED", "RECOVERY_NOT_CONFIRMED"]) }).safeParse(recovered.error);
          return { ok: false as const, error: failure.success ? failure.data.code : "UNAVAILABLE" as const };
        }
        if (!z.strictObject({ recovered: z.literal(true) }).safeParse(recovered.data).success) return { ok: false as const, error: "RECOVERY_NOT_CONFIRMED" as const };
        const checked = await api.listFactors(); if (checked.error) throw Error();
        if (factors.parse(checked.data).all.some(f => f.status === "verified" || f.id === pending[0]!.id)) return { ok: false as const, error: "RECOVERY_NOT_CONFIRMED" as const };
        ownEnrollment = null;
        recoverableEnrollment = null;
        return { ok: true as const };
      } catch { return { ok: false as const, error: "UNAVAILABLE" as const }; }
      finally { mutating = false; }
    },
    async verify(factorId: string, code: string) {
      if (!z.uuid().safeParse(factorId).success || !/^\d{6}$/u.test(code)) return { ok: false as const, error: "INVALID_CODE" as const };
      if (mutating) return { ok: false as const, error: "UNAVAILABLE" as const };
      mutating = true;
      try {
        const current = await read();
        if (!current.factors.some(f => f.id === factorId) && ownEnrollment !== factorId) return { ok: false as const, error: "NO_FACTOR" as const };
        const result = await api.challengeAndVerify({ factorId, code });
        if (result.error) return { ok: false as const, error: "INVALID_CODE" as const };
        const confirmed = await read();
        if (!confirmed.fresh || !confirmed.factors.some(f => f.id === factorId)) return { ok: false as const, error: "VERIFICATION_NOT_CONFIRMED" as const };
        ownEnrollment = null;
        return { ok: true as const };
      } catch { return { ok: false as const, error: "UNAVAILABLE" as const }; }
      finally { mutating = false; }
    },
  });
}

/** Same-origin recovery intent only. Passwords, tokens and setup material are
 * never accepted here. Server ownership/RBAC/fresh-login checks are independent. */
export async function submitPrivateBetaMfaRecovery(value: { factorId: string; confirmed: true }, network: typeof fetch = fetch): ApiResult {
  try {
    if (!z.uuid().safeParse(value.factorId).success || value.confirmed !== true) throw Error();
    const response = await network("/api/v1/admin/private-beta/mfa-recovery", { method: "POST", credentials: "same-origin", redirect: "error", signal: AbortSignal.timeout(15000),
      headers: { "content-type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ factor_id: value.factorId, confirmed: "yes" }) });
    if (!response.body) throw Error();
    const reader = response.body.getReader(), chunks: Uint8Array[] = []; let size = 0;
    try { for (;;) { const p = await reader.read(); if (p.done) break; size += p.value.byteLength; if (size > 2048) throw Error(); chunks.push(p.value); } }
    finally { void reader.cancel().catch(() => undefined); reader.releaseLock(); }
    const raw = new Uint8Array(size); let offset = 0; for (const c of chunks) { raw.set(c, offset); offset += c.length; }
    const body: unknown = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(raw));
    if (response.ok && z.strictObject({ recovered: z.literal(true) }).safeParse(body).success) return { data: { recovered: true }, error: null };
    const failure = z.object({ error: z.enum(["RECOVERY_REAUTH_REQUIRED", "RECOVERY_BLOCKED", "RECOVERY_NOT_CONFIRMED"]) }).safeParse(body);
    return { data: null, error: { code: failure.success ? failure.data.error : "RECOVERY_NOT_CONFIRMED" } };
  } catch { return { data: null, error: { code: "RECOVERY_NOT_CONFIRMED" } }; }
}
